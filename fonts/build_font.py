#!/usr/bin/env python3
"""Turn Fusion Pixel Font's 12px monospaced Traditional Chinese (Taiwan) BDF into ../hooks/fontdata.ts.

    python3 build_font.py fusion-pixel-12px-monospaced-zh_tw.bdf [fusion-pixel-12px-monospaced-ja.bdf]

Keeps ASCII, Latin-1, common punctuation and symbols, full-width forms, and the CJK characters
Big5 holds (about 13,000, the ones Traditional Chinese text uses), so the module stays small.
Given the Japanese BDF too, adds from it the kana and the kanji Shift_JIS holds that Big5 lacks (効, 楽...).
Each glyph is 12 rows: one byte per row for a 6-pixel glyph, two for a 12-pixel one.
"""
import base64
import sys
from pathlib import Path

H = 12
RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x2010, 0x205F), (0x2190, 0x21FF), (0x2460, 0x24FF),
          (0x25A0, 0x25FF), (0x2600, 0x26FF), (0x3000, 0x303F), (0x3100, 0x312F), (0xFF00, 0xFFEF)]


def wanted(code: int) -> bool:
    if any(a <= code <= b for a, b in RANGES):
        return True
    if 0x4E00 <= code <= 0x9FFF:
        try:
            chr(code).encode('big5')
            return True
        except UnicodeEncodeError:
            return False
    return False


def wanted_ja(code: int) -> bool:
    if 0x3040 <= code <= 0x30FF or 0x31F0 <= code <= 0x31FF:
        return True
    if 0x4E00 <= code <= 0x9FFF:
        try:
            chr(code).encode('big5')
            return False
        except UnicodeEncodeError:
            pass
        try:
            chr(code).encode('shift_jis')
            return True
        except UnicodeEncodeError:
            return False
    return False


def parse(path: Path, want=wanted):
    ascent = None
    glyphs = {}
    lines = iter(path.read_text(encoding='utf-8', errors='replace').splitlines())
    for line in lines:
        if line.startswith('FONT_ASCENT'):
            ascent = int(line.split()[1])
        if not line.startswith('STARTCHAR'):
            continue
        code = dx = bbx = None
        for line in lines:
            key, _, rest = line.partition(' ')
            if key == 'ENCODING':
                code = int(rest.split()[0])
            elif key == 'DWIDTH':
                dx = int(rest.split()[0])
            elif key == 'BBX':
                bbx = [int(v) for v in rest.split()]
            elif key == 'BITMAP':
                break
        w, h, xoff, yoff = bbx
        bitmap = []
        for line in lines:
            if line.startswith('ENDCHAR'):
                break
            bitmap.append(int(line, 16) >> (len(line) * 4 - w))
        if code is None or code < 0 or dx not in (6, 12) or not want(code):
            continue
        rows = [0] * H
        top = ascent - (yoff + h)
        for r, bits in enumerate(bitmap):
            y = top + r
            if 0 <= y < H:
                shift = dx - xoff - w
                rows[y] = (bits << shift if shift >= 0 else bits >> -shift) & ((1 << dx) - 1)
        glyphs[code] = (dx, rows)
    return glyphs


def pack(glyphs, dx):
    codes = sorted(c for c, (w, _) in glyphs.items() if w == dx)
    out = bytearray()
    for c in codes:
        for row in glyphs[c][1]:
            out += row.to_bytes(2 if dx > 8 else 1, 'big')
    deltas, prev = [], 0
    for c in codes:
        deltas.append(base36(c - prev))
        prev = c
    return ','.join(deltas), base64.b64encode(bytes(out)).decode(), len(codes)


def base36(n: int) -> str:
    s = ''
    while True:
        n, r = divmod(n, 36)
        s = '0123456789abcdefghijklmnopqrstuvwxyz'[r] + s
        if not n:
            return s


def main():
    glyphs = parse(Path(sys.argv[1]))
    if len(sys.argv) > 2:
        for code, g in parse(Path(sys.argv[2]), wanted_ja).items():
            glyphs.setdefault(code, g)
    ch, bh, nh = pack(glyphs, 6)
    cf, bf, nf = pack(glyphs, 12)
    out = Path(__file__).resolve().parent.parent / 'hooks' / 'fontdata.ts'
    out.write_text(
        '// Generated by ../fonts/build_font.py from Fusion Pixel Font 12px (SIL OFL 1.1). Do not edit.\n'
        f'// {nh} half-width and {nf} full-width glyphs.\n'
        f"export const CODES_HALF = '{ch}'\n"
        f"export const BITS_HALF = '{bh}'\n"
        f"export const CODES_FULL = '{cf}'\n"
        f"export const BITS_FULL = '{bf}'\n",
        encoding='utf-8')
    print(f'{out}: {nh} half + {nf} full glyphs, {out.stat().st_size // 1024} KB')


if __name__ == '__main__':
    main()
